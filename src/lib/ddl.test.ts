import { describe, expect, test } from 'bun:test'
import {
  addColumnSql,
  addConstraintSql,
  alterColumnSql,
  createDatabaseSql,
  createIndexSql,
  createSchemaSql,
  createTableSql,
  ddlScript,
  defaultExpression,
  describedColumnSql,
  schemaNameProblem,
} from './ddl'

const col = (over: Partial<Parameters<typeof addColumnSql>[2]> = {}) => ({
  name: 'title',
  type: 'text',
  nullable: true,
  defaultValue: '',
  comment: '',
  ...over,
})

describe('ddl', () => {
  test('defaults: words are quoted for text, expressions are kept', () => {
    expect(defaultExpression('draft', 'text')).toBe("'draft'")
    expect(defaultExpression("it's", 'varchar(20)')).toBe("'it''s'")
    expect(defaultExpression('now()', 'timestamptz')).toBe('now()')
    expect(defaultExpression('0', 'integer')).toBe('0')
    expect(defaultExpression("'x'", 'text')).toBe("'x'")
    expect(defaultExpression('pending', 'order_status', new Set(['order_status']))).toBe("'pending'")
    expect(defaultExpression('CURRENT_TIMESTAMP', 'timestamptz')).toBe('CURRENT_TIMESTAMP')
  })

  test('create table', () => {
    const sql = createTableSql('public', 'notes', [
      col({ name: 'id', type: 'bigint', identity: true, primaryKey: true, nullable: false }),
      col({ name: 'body', nullable: false, comment: 'The text' }),
      col({ name: 'created_at', type: 'timestamptz', defaultValue: 'now()', nullable: false }),
    ])
    expect(sql[0]).toBe(
      'CREATE TABLE "public"."notes" (\n  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n  "body" text NOT NULL,\n  "created_at" timestamptz DEFAULT now() NOT NULL\n)',
    )
    expect(sql[1]).toBe(`COMMENT ON COLUMN "public"."notes"."body" IS 'The text'`)
  })

  test('composite primary key', () => {
    const sql = createTableSql('s', 't', [col({ name: 'a', primaryKey: true }), col({ name: 'b', primaryKey: true })])
    expect(sql[0]).toContain('  PRIMARY KEY ("a", "b")')
  })

  test('alter column only emits what changed', () => {
    const before = col({ name: 'title', type: 'text', nullable: true })
    expect(alterColumnSql('public', 't', before, before)).toEqual([])
    const out = alterColumnSql('public', 't', before, { ...before, name: 'name', nullable: false, defaultValue: 'x' })
    expect(out).toEqual([
      'ALTER TABLE "public"."t" RENAME COLUMN "title" TO "name"',
      `ALTER TABLE "public"."t" ALTER COLUMN "name" SET DEFAULT 'x'`,
      'ALTER TABLE "public"."t" ALTER COLUMN "name" SET NOT NULL',
    ])
  })

  test('index and constraints', () => {
    expect(
      createIndexSql('public', 'orders', {
        name: '',
        columns: ['status', 'placed_at'],
        unique: false,
        method: 'btree',
        where: '',
      }),
    ).toBe('CREATE INDEX "orders_status_placed_at_idx" ON "public"."orders" ("status", "placed_at")')
    expect(
      addConstraintSql('public', 'orders', {
        type: 'foreign',
        name: '',
        columns: ['customer_id'],
        refSchema: 'public',
        refTable: 'customers',
        refColumns: ['id'],
        onDelete: 'CASCADE',
        onUpdate: 'NO ACTION',
      }),
    ).toBe(
      'ALTER TABLE "public"."orders" ADD FOREIGN KEY ("customer_id") REFERENCES "public"."customers" ("id") ON DELETE CASCADE',
    )
  })

  test('scripts run as one transaction', () => {
    expect(ddlScript(['A'])).toBe('A;')
    expect(ddlScript(['A', 'B'])).toBe('BEGIN;\nA;\nB;\nCOMMIT;')
  })
})

describe('describedColumnSql (catalog columns to CREATE TABLE lines)', () => {
  const base = { name: 'b', type: 'integer', identity: '', generated: '', defaultValue: null, nullable: true }

  test('plain column, with and without default and NOT NULL', () => {
    expect(describedColumnSql(base)).toBe('  "b" integer')
    expect(describedColumnSql({ ...base, defaultValue: '0', nullable: false })).toBe('  "b" integer DEFAULT 0 NOT NULL')
  })

  test('identity columns', () => {
    expect(describedColumnSql({ ...base, identity: 'a', nullable: false })).toBe(
      '  "b" integer GENERATED ALWAYS AS IDENTITY NOT NULL',
    )
    expect(describedColumnSql({ ...base, identity: 'd' })).toBe('  "b" integer GENERATED BY DEFAULT AS IDENTITY')
  })

  test('STORED generated column (PostgreSQL 12 and later)', () => {
    expect(describedColumnSql({ ...base, generated: 's', defaultValue: '(a * 3)' })).toBe(
      '  "b" integer GENERATED ALWAYS AS ((a * 3)) STORED',
    )
  })

  test('VIRTUAL generated column (PostgreSQL 18) is not a DEFAULT', () => {
    expect(describedColumnSql({ ...base, generated: 'v', defaultValue: '(a * 2)' })).toBe(
      '  "b" integer GENERATED ALWAYS AS ((a * 2))',
    )
  })
})

describe('schemas', () => {
  test('CREATE SCHEMA with a plain name', () => {
    expect(createSchemaSql('billing')).toEqual(['CREATE SCHEMA "billing"'])
  })

  test('names are trimmed and quoted, with double quotes and mixed case kept', () => {
    expect(createSchemaSql('  My"Schema  ')).toEqual(['CREATE SCHEMA "My""Schema"'])
    expect(createSchemaSql('Billing')).toEqual(['CREATE SCHEMA "Billing"'])
  })

  test('a comment adds COMMENT ON SCHEMA, with single quotes escaped', () => {
    expect(createSchemaSql('billing', "Owner's invoices")).toEqual([
      'CREATE SCHEMA "billing"',
      `COMMENT ON SCHEMA "billing" IS 'Owner''s invoices'`,
    ])
  })

  test('a blank comment gives one statement', () => {
    expect(createSchemaSql('billing', '   ')).toEqual(['CREATE SCHEMA "billing"'])
  })

  test('createDatabaseSql: a plain name', () => {
    expect(createDatabaseSql('analytics')).toEqual(['CREATE DATABASE "analytics"'])
  })

  test('createDatabaseSql: trimmed and quoted, with double quotes, spaces and mixed case kept', () => {
    expect(createDatabaseSql('  My "Shop"  ')).toEqual(['CREATE DATABASE "My ""Shop"""'])
    expect(createDatabaseSql('Sales 2026')).toEqual(['CREATE DATABASE "Sales 2026"'])
  })

  test('schemaNameProblem: empty, taken, pg_ prefix, valid', () => {
    expect(schemaNameProblem('  ')).toBe('Required')
    expect(schemaNameProblem('billing', ['billing'])).toBe('Already used')
    expect(schemaNameProblem('pg_temp')).toBe('Names starting with pg_ are reserved')
    // PostgreSQL only reserves the lowercase prefix
    expect(schemaNameProblem('PG_custom')).toBeNull()
    expect(schemaNameProblem('billing', ['sales'])).toBeNull()
  })
})
